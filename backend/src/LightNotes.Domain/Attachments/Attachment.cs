using LightNotes.Domain.Common;

namespace LightNotes.Domain.Attachments;

/// <summary>Metadata of an uploaded image.</summary>
public sealed class Attachment
{
    public const int MaxSizeBytes = 10 * 1024 * 1024;
    public const int MaxStorageKeyLength = 200;
    private const int Sha256HexLength = 64;

    public static IReadOnlySet<string> AllowedContentTypes { get; } =
        new HashSet<string>(["image/jpeg", "image/png", "image/webp", "image/gif"]);

    public Guid Id { get; private set; }

    public Guid UserId { get; private set; }

    public Guid NoteId { get; private set; }

    public string ContentType { get; private set; } = "";

    public long SizeBytes { get; private set; }

    /// <summary>Opaque blob key generated by the server.</summary>
    public string StorageKey { get; private set; } = "";

    /// <summary>Lowercase hex SHA-256 of the file.</summary>
    public string Sha256 { get; private set; } = "";

    public DateTimeOffset CreatedAt { get; private set; }

    private Attachment() { }

    public static Attachment Create(
        Guid id,
        Guid userId,
        Guid noteId,
        string contentType,
        long sizeBytes,
        string storageKey,
        string sha256,
        DateTimeOffset createdAt)
    {
        Guard.ClientId(id);
        Guard.ClientId(noteId);
        Guard.OwnerId(userId);

        var type = contentType.Trim().ToLowerInvariant();

        if (!AllowedContentTypes.Contains(type))
        {
            throw new DomainException(DomainErrorCodes.AttachmentTypeNotAllowed, "Content type is not allowed.");
        }

        if (sizeBytes <= 0)
        {
            throw new DomainException(DomainErrorCodes.AttachmentSizeInvalid, "File is empty.");
        }

        if (sizeBytes > MaxSizeBytes)
        {
            throw new DomainException(DomainErrorCodes.AttachmentTooLarge, $"File is larger than {MaxSizeBytes} bytes.");
        }

        if (string.IsNullOrWhiteSpace(storageKey) || storageKey.Length > MaxStorageKeyLength)
        {
            throw new DomainException(DomainErrorCodes.AttachmentStorageKeyInvalid, "Storage key is invalid.");
        }

        if (sha256.Length != Sha256HexLength || !sha256.All(char.IsAsciiHexDigit))
        {
            throw new DomainException(DomainErrorCodes.AttachmentHashInvalid, "SHA-256 must be 64 hex characters.");
        }

        return new Attachment
        {
            Id = id,
            UserId = userId,
            NoteId = noteId,
            ContentType = type,
            SizeBytes = sizeBytes,
            StorageKey = storageKey,
            Sha256 = sha256.ToLowerInvariant(),
            CreatedAt = createdAt.ToUniversalTime(),
        };
    }
}
